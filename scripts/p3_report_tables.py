"""P3-T5/T6/T7/T9 — render the aggregated results as Markdown tables (data/manifests/phase3/results/<pop>/tables.md).

    python scripts/p3_report_tables.py --population main

Pure formatting of p3_aggregate.py outputs; no statistics are computed here. Quality and identity tables are kept
in separate sections (P3-T1 §7).
"""

from __future__ import annotations

import argparse

from fes_data.common import read_csv_gz, repo_path

ORDER = ["B0", "B1", "B2", "B2c", "A1", "A2", "A3", "A4", "A5"]
FAM = ["lowres", "gaussblur", "motionblur", "noise", "jpeg", "underexposure", "lowcontrast", "combined", "realistic2"]
SEV = ["mild", "moderate", "severe", "extreme"]
MARK = {"better": "▲", "worse": "▼", "tie": "≈"}


def f(x, nd=3):
    try:
        return f"{float(x):.{nd}f}"
    except (TypeError, ValueError):
        return "—"


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--population", default="main")
    args = ap.parse_args()
    d = repo_path(f"data/manifests/phase3/results/{args.population}")
    cells = read_csv_gz(d / "cells.csv.gz")
    deltas = read_csv_gz(d / "deltas.csv.gz")
    ident = read_csv_gz(d / "identity.csv.gz")
    configs = [c for c in ORDER if any(r["config_id"] == c for r in cells)]
    out = [f"# Phase 3 result tables — population `{args.population}`\n",
           "Generated by `scripts/p3_report_tables.py` from `results/<pop>/*.csv.gz`. ▲ better / ▼ worse / ≈ no "
           "detectable difference vs the stated baseline (95 % cluster-bootstrap CI over references).\n"]

    def dl(cfg, base, kind, grp):
        return next((r for r in deltas if r["config_id"] == cfg and r["baseline"] == base and r["group_kind"] == kind
                     and r["group"] == grp), None)

    def idr(cfg, kind, grp):
        return next((r for r in ident if r["config_id"] == cfg and r["group_kind"] == kind and r["group"] == grp), None)

    # ---------- quality: absolute means per family
    for m, nd in (("lpips", 3), ("psnr", 2), ("ssim", 3)):
        out.append(f"\n## Quality — mean {m.upper()} per family (all severities pooled)\n")
        out.append("| Config | " + " | ".join(FAM) + " |")
        out.append("|---" * (len(FAM) + 1) + "|")
        for c in configs:
            vals = []
            for fam in FAM:
                rs = [r for r in cells if r["config_id"] == c and r["cell"].startswith(fam + "-")]
                v = [float(r[f"{m}_mean"]) for r in rs if r[f"{m}_mean"] != ""]
                vals.append(f(sum(v) / len(v), nd) if v else "—")
            out.append(f"| {c} | " + " | ".join(vals) + " |")

    # ---------- quality: paired deltas vs B0 by family / severity
    for m in ("lpips", "psnr"):
        for kind, groups in (("family", FAM), ("severity", SEV)):
            out.append(f"\n## Quality — Δ{m.upper()} vs B0 by {kind} (mean [95 % CI] verdict)\n")
            out.append("| Config | " + " | ".join(groups) + " | all |")
            out.append("|---" * (len(groups) + 2) + "|")
            for c in configs:
                if c == "B0":
                    continue
                row = []
                for g in groups + ["all"]:
                    r = dl(c, "B0", "all" if g == "all" else kind, g)
                    row.append("—" if r is None else
                               f"{f(r[f'd_{m}'])} [{f(r[f'd_{m}_lo'])}, {f(r[f'd_{m}_hi'])}] {MARK[r[f'd_{m}_verdict']]}")
                out.append(f"| {c} | " + " | ".join(row) + " |")

    # ---------- per cell LPIPS medians (distribution view)
    out.append("\n## Quality — LPIPS median [p5–p95] per cell\n")
    cell_ids = []
    for fam in FAM:
        for s in SEV:
            if any(r["cell"] == f"{fam}-{s}" for r in cells):
                cell_ids.append(f"{fam}-{s}")
    out.append("| Cell | " + " | ".join(configs) + " |")
    out.append("|---" * (len(configs) + 1) + "|")
    for cell in cell_ids:
        row = []
        for c in configs:
            r = next((r for r in cells if r["config_id"] == c and r["cell"] == cell), None)
            row.append("—" if r is None else f"{f(r['lpips_median'])} [{f(r['lpips_p5'], 2)}–{f(r['lpips_p95'], 2)}]")
        out.append(f"| {cell} | " + " | ".join(row) + " |")

    # ---------- identity (separate section)
    out.append("\n---\n\n# Identity (SFace, single evaluator) — reported separately from quality\n")
    for kind, groups in (("family", FAM), ("severity", SEV)):
        out.append(f"\n## Identity — mean cos(output, reference) and ΔID vs B0 by {kind}\n")
        out.append("| Config | " + " | ".join(groups) + " | all |")
        out.append("|---" * (len(groups) + 2) + "|")
        for c in configs:
            row = []
            for g in groups + ["all"]:
                i = idr(c, "all" if g == "all" else kind, g)
                r = dl(c, "B0", "all" if g == "all" else kind, g) if c != "B0" else None
                s = f(i["id_cos_mean"]) if i else "—"
                if r:
                    s += f" ({f(r['d_id_cos'])} {MARK[r['d_id_cos_verdict']]})"
                row.append(s)
            out.append(f"| {c} | " + " | ".join(row) + " |")
    out.append("\n## Identity — operating point and drop rates (all cells)\n")
    out.append("| Config | n | mean cos | p5 cos | TAR@FAR1e-2 | observed FAR | mean impostor cos | "
               "frac gain<0 | frac drop > 1-px-shift p99 |")
    out.append("|---|---|---|---|---|---|---|---|---|")
    for c in configs:
        i = idr(c, "all", "all")
        out.append(f"| {c} | {i['n']} | {f(i['id_cos_mean'])} | {f(i['id_cos_p5'])} | {f(i['tar_at_far1e-2'])} | "
                   f"{f(i['far_observed'], 4)} | {f(i['imp_cos_mean'])} | {f(i['frac_gain_neg'])} | "
                   f"{f(i['frac_drop_beyond_shift1px_p99'])} |")
    out.append("\n## Identity — TAR@FAR1e-2 by severity\n")
    out.append("| Config | " + " | ".join(SEV) + " |")
    out.append("|---" * (len(SEV) + 1) + "|")
    for c in configs:
        out.append(f"| {c} | " + " | ".join(f(idr(c, 'severity', s)['tar_at_far1e-2']) if idr(c, 'severity', s)
                                            else "—" for s in SEV) + " |")

    # ---------- geometry
    out.append("\n## Geometry — mean landmark NME and YuNet detection rate by severity\n")
    out.append("| Config | " + " | ".join(f"{s} NME / det" for s in SEV) + " |")
    out.append("|---" * (len(SEV) + 1) + "|")
    for c in configs:
        row = []
        for s in SEV:
            rs = [r for r in cells if r["config_id"] == c and r["cell"].endswith("-" + s)]
            n = [float(r["lm_nme_mean"]) for r in rs if r["lm_nme_mean"] != ""]
            dt = [float(r["det_rate"]) for r in rs if r["det_rate"] not in ("", "nan")]
            row.append(f"{f(sum(n) / len(n)) if n else '—'} / {f(sum(dt) / len(dt), 2) if dt else '—'}")
        out.append(f"| {c} | " + " | ".join(row) + " |")
    (d / "tables.md").write_text("\n".join(out) + "\n", encoding="utf-8")
    print(d / "tables.md")


if __name__ == "__main__":
    main()
